from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.units import cm
import os
from datetime import datetime

PDF_DIR = "receipts"
os.makedirs(PDF_DIR, exist_ok=True)
FINES_DIR = "fines"
os.makedirs(FINES_DIR, exist_ok=True)

def generate_receipt(booking, user) -> str:
    filename = f"{PDF_DIR}/receipt_{booking.id}_{int(datetime.utcnow().timestamp())}.pdf"
    doc = SimpleDocTemplate(filename, pagesize=A4, topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story = []

    title_style = ParagraphStyle("title", parent=styles["Heading1"], textColor=colors.HexColor("#1D9E75"), fontSize=20, alignment=1)
    story.append(Paragraph("TPMS – Parking Receipt", title_style))
    story.append(Spacer(1, 0.5*cm))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#1D9E75")))
    story.append(Spacer(1, 0.5*cm))

    data = [
        ["Receipt No.", f"TPMS-{booking.id:06d}"],
        ["User Name", user.name],
        ["Email", user.email],
        ["Vehicle No.", booking.vehicle_number or "N/A"],
        ["Zone ID", str(booking.zone_id)],
        ["Slot ID", str(booking.slot_id)],
        ["Start Time", str(booking.start_time)[:16]],
        ["End Time", str(booking.end_time)[:16]],
        ["Amount Paid", f"₹ {booking.total_amount:.2f}"],
        ["Payment ID", booking.payment_id or "N/A"],
        ["Status", booking.status.value.upper()],
        ["Generated At", str(datetime.utcnow())[:16]],
    ]
    table = Table(data, colWidths=[6*cm, 10*cm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (0,-1), colors.HexColor("#E1F5EE")),
        ("TEXTCOLOR",  (0,0), (0,-1), colors.HexColor("#085041")),
        ("FONTNAME",   (0,0), (0,-1), "Helvetica-Bold"),
        ("GRID",       (0,0), (-1,-1), 0.5, colors.HexColor("#5DCAA5")),
        ("ROWBACKGROUNDS", (0,0), (-1,-1), [colors.white, colors.HexColor("#F5FEFB")]),
        ("PADDING",    (0,0), (-1,-1), 8),
    ]))
    story.append(table)
    story.append(Spacer(1, 1*cm))
    story.append(Paragraph("Thank you for using TPMS. Drive Safe!", styles["Normal"]))
    doc.build(story)
    return filename

def generate_fine_pdf(complaint) -> str:
    filename = f"{FINES_DIR}/fine_{complaint.id}_{int(datetime.utcnow().timestamp())}.pdf"
    doc = SimpleDocTemplate(filename, pagesize=A4, topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story = []

    title_style = ParagraphStyle("title", parent=styles["Heading1"], textColor=colors.HexColor("#D85A30"), fontSize=20, alignment=1)
    story.append(Paragraph("TPMS – Traffic Violation Fine", title_style))
    story.append(Spacer(1, 0.5*cm))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#D85A30")))
    story.append(Spacer(1, 0.5*cm))

    data = [
        ["Fine No.",          f"FINE-{complaint.id:06d}"],
        ["Complaint Type",    complaint.complaint_type.value.replace("_", " ").title()],
        ["Location Lat",      str(complaint.latitude)],
        ["Location Long",     str(complaint.longitude)],
        ["Description",       complaint.description or "N/A"],
        ["Status",            complaint.status.value.upper()],
        ["Reported At",       str(complaint.created_at)[:16]],
        ["Photo Evidence",    "Attached" if complaint.photo_url else "None"],
        ["Fine Amount",       "₹ 500"],
        ["Issued By",         "TPMS Auto-System"],
    ]
    table = Table(data, colWidths=[6*cm, 10*cm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (0,-1), colors.HexColor("#FAECE7")),
        ("TEXTCOLOR",  (0,0), (0,-1), colors.HexColor("#712B13")),
        ("FONTNAME",   (0,0), (0,-1), "Helvetica-Bold"),
        ("GRID",       (0,0), (-1,-1), 0.5, colors.HexColor("#F0997B")),
        ("ROWBACKGROUNDS", (0,0), (-1,-1), [colors.white, colors.HexColor("#FFFAF8")]),
        ("PADDING",    (0,0), (-1,-1), 8),
    ]))
    story.append(table)
    story.append(Spacer(1, 1*cm))
    story.append(Paragraph("This fine has been generated by the TPMS automated system and forwarded to traffic police.", styles["Normal"]))
    doc.build(story)
    return filename
